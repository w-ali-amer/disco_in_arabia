# emit QnlpFormal/Data.lean from data/s30.json (integer data only; Lean recomputes every value)
import json, sys
d = json.load(open(sys.argv[1]))
def v(p): return "![%d, %d]" % tuple(p)
rows = []
for a in range(6):
    rows.append("![" + ", ".join(v(d["psi"]["%d,%d" % (a, b)]) if a != b else "![1, 0]" for b in range(6)) + "]")
enc = []
for a in range(6):
    enc.append("![" + ", ".join(("true" if d["enc"]["%d,%d" % (a, b)] == 1 else "false") if a != b else "false" for b in range(6)) + "]")
bits = lambda l: "![" + ", ".join("true" if (l >> i) & 1 else "false" for i in range(6)) + "]"
print("""-- generated by scripts/emit_lean.py from data/s30.json; numbers here are data, not trusted results
import Mathlib

namespace QnlpFormal

/-- state vectors psi a b of the explicit one-qubit strategy S30 (diagonal entries unused) -/
def psi30 : Fin 6 → Fin 6 → Fin 2 → ℚ :=
  ![%s]

/-- measurement directions m v of S30 -/
def m30 : Fin 6 → Fin 2 → ℚ := ![%s]

/-- an optimal classical encoder (true = message 1) -/
def enc0 : Fin 6 → Fin 6 → Bool :=
  ![%s]

/-- an optimal pair of classical decoders (bit a = answer for class a, false = position 0) -/
def dec0 : Bool → Fin 6 → Bool := fun s => if s then %s else %s

end QnlpFormal""" % (",\n    ".join(rows), ", ".join(v(p) for p in d["m"]), ",\n    ".join(enc), bits(d["l1"]), bits(d["l0"])))
