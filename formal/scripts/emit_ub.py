# -*- coding: utf-8 -*-
"""emit_ub.py -- doc 141: emit data/ub.json as QnlpFormal/UbData.lean (lam table, mu, LDL squares). Lean re-checks the identity."""
import json, sys
from fractions import Fraction as F
d = json.load(open(sys.argv[1])); fr = lambda t: F(t[0], t[1])
def lit(q):
    q = F(q)
    s = "(%d : ℝ)" % q.numerator if q.denominator == 1 else "((%d : ℝ) / %d)" % (q.numerator, q.denominator)
    return s
lam = {tuple(map(int, k.split(","))): fr(v) for k, v in d["lam"].items()}
L = [[0] * 6 for _ in range(6)]
for (a, b), v in lam.items(): L[a][b] = L[b][a] = v
mu = [fr(m) for m in d["mu"]]; Lf = [[fr(x) for x in row] for row in d["ldl_L"]]; dd = [fr(x) for x in d["ldl_d"]]
rows = ",\n  ".join("![" + ", ".join(lit(x) for x in r) + "]" for r in L)
sq = []
for i in range(6):
    lin = " + ".join("%s * y %d" % (lit(Lf[j][i]), j) for j in range(i, 6) if Lf[j][i] != 0)
    sq.append("%s * (%s) ^ 2" % (lit(dd[i]), lin))
out = """/- generated by scripts/emit_ub.py from data/ub.json (doc 141); Lean re-checks every identity. -/
import Mathlib

set_option linter.style.longLine false

namespace QnlpFormal

/-- AM-GM weights λ_ab (symmetric, diagonal unused). -/
noncomputable def lamT : Fin 6 → Fin 6 → ℝ := ![
  %s]

/-- diagonal shifts μ_v. -/
noncomputable def muT : Fin 6 → ℝ := ![%s]

/-- the LDLᵀ squares of diag(μ) − L. -/
noncomputable def ldlSq (y : Fin 6 → ℝ) : ℝ :=
  %s

/-- pivots of the LDLᵀ factorisation. -/
theorem ldl_pivots_pos : %s := by norm_num

/-- the exact bound U. -/
noncomputable def Ubound : ℝ := %s

end QnlpFormal
""" % (rows, ", ".join(lit(m) for m in mu), " +\n  ".join(sq), " ∧ ".join("(0 : ℝ) < %s" % lit(x) for x in dd), lit(fr(d["U"])))
open(sys.argv[2], "w").write(out)
